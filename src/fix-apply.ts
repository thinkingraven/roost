import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import type { FileChange, FixPlan, RepoFix } from './fix.js';

/**
 * `roost verdicts --fix --write`: the only place roost runs git. Creates one branch per repo,
 * `git rm`s the files `fix.ts` planned, and commits. Never pushes, never calls a hosting API —
 * that stays a manual, deliberate step (`git push && gh pr create`), same as roost's one existing
 * network exception (`export --send`) stays its own explicit opt-in.
 */

export interface RepoApplyResult {
  repoRoot: string;
  branch?: string;
  applied: FileChange[];
  skipped: { change: FileChange; reason: string }[];
  /** Set when nothing in this repo was touched at all (not a git repo, or a dirty tree). */
  repoSkipReason?: string;
}

export interface ApplyResult {
  repos: RepoApplyResult[];
}

function git(repoRoot: string, args: string[]): string {
  return execFileSync('git', ['-C', repoRoot, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
}

function branchExists(repoRoot: string, branch: string): boolean {
  try { git(repoRoot, ['rev-parse', '--verify', '--quiet', branch]); return true; } catch { return false; }
}

/** `base`, or `base-2`, `base-3`… the first one not already taken. */
function freeBranchName(repoRoot: string, base: string): string {
  if (!branchExists(repoRoot, base)) return base;
  for (let n = 2; ; n++) {
    const name = `${base}-${n}`;
    if (!branchExists(repoRoot, name)) return name;
  }
}

function commitMessage(changes: FileChange[]): string {
  const summary = changes.length === 1 ? '1 skill' : `${changes.length} skills`;
  const lines = changes.map((c) => `- ${c.relPath}: ${c.reason}`);
  return `roost: retire or merge ${summary} rookery and session logs say are unused\n\n${lines.join('\n')}\n\nGenerated by \`roost verdicts --fix --write\`. Never pushed; nothing opened.`;
}

function applyToRepo(repo: RepoFix): RepoApplyResult {
  const { repoRoot, changes } = repo;

  try { git(repoRoot, ['rev-parse', '--is-inside-work-tree']); } catch {
    return { repoRoot, applied: [], skipped: [], repoSkipReason: 'not a git repository' };
  }

  let status: string;
  try { status = git(repoRoot, ['status', '--porcelain']); } catch (err) {
    return { repoRoot, applied: [], skipped: [], repoSkipReason: `git status failed: ${(err as Error).message}` };
  }
  if (status) return { repoRoot, applied: [], skipped: [], repoSkipReason: 'uncommitted changes — commit or stash first' };

  const present = changes.filter((c) => existsSync(c.absolutePath));
  const missing = changes.filter((c) => !existsSync(c.absolutePath)).map((change) => ({ change, reason: 'file no longer exists' }));
  if (!present.length) return { repoRoot, applied: [], skipped: missing };

  const original = git(repoRoot, ['branch', '--show-current']);
  const branch = freeBranchName(repoRoot, `roost/retire-skills-${new Date().toISOString().slice(0, 10)}`);
  try {
    git(repoRoot, ['checkout', '-b', branch]);
    git(repoRoot, ['rm', '--quiet', '--', ...present.map((c) => c.relPath)]);
    git(repoRoot, ['commit', '--quiet', '-m', commitMessage(present)]);
  } catch (err) {
    // Best effort: leave the repo as we found it rather than stranded on a half-made branch.
    try { if (original) git(repoRoot, ['checkout', '--quiet', original]); } catch { /* leave as-is */ }
    try { git(repoRoot, ['branch', '-D', branch]); } catch { /* leave as-is */ }
    const reason = `git failed: ${(err as Error).message.split('\n')[0]}`;
    return { repoRoot, applied: [], skipped: [...present.map((change) => ({ change, reason })), ...missing] };
  }

  return { repoRoot, branch, applied: present, skipped: missing };
}

export function applyFix(plan: FixPlan): ApplyResult {
  return { repos: plan.repos.map(applyToRepo) };
}
